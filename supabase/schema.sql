-- ============================================================================
--  Foreign keys faltantes (idempotentes, cada uma isolada: se houver dados
--  orfaos a constraint e pulada com NOTICE e o script segue rodando).
-- ============================================================================
do $$
begin
  -- produtos.categoria_id -> categorias(id): apagar categoria nao apaga produto
  if not exists (
    select 1 from pg_constraint where conname = 'fk_produtos_categoria'
      and conrelid = 'public.produtos'::regclass
  ) then
    begin
      alter table public.produtos
        add constraint fk_produtos_categoria
        foreign key (categoria_id) references public.categorias(id) on delete set null;
    exception when others then
      raise notice 'fk_produtos_categoria nao criada (dados orfaos?): %', sqlerrm;
    end;
  end if;

  -- produtos.fornecedor_id -> fornecedores(id)
  if not exists (
    select 1 from pg_constraint where conname = 'fk_produtos_fornecedor'
      and conrelid = 'public.produtos'::regclass
  ) then
    begin
      alter table public.produtos
        add constraint fk_produtos_fornecedor
        foreign key (fornecedor_id) references public.fornecedores(id) on delete set null;
    exception when others then
      raise notice 'fk_produtos_fornecedor nao criada (dados orfaos?): %', sqlerrm;
    end;
  end if;

  -- movimentacoes.produto_id -> produtos(id): historico nao pode ser órfão,
  -- mas apagar produto com histórico fica bloqueado (NO ACTION) — decisão segura.
  if not exists (
    select 1 from pg_constraint where conname = 'fk_movimentacoes_produto'
      and conrelid = 'public.movimentacoes'::regclass
  ) then
    begin
      alter table public.movimentacoes
        add constraint fk_movimentacoes_produto
        foreign key (produto_id) references public.produtos(id);
    exception when others then
      raise notice 'fk_movimentacoes_produto nao criada (dados orfaos?): %', sqlerrm;
    end;
  end if;

  -- solicitacoes.loja_id -> lojas(id): coluna NOT NULL, sem ON DELETE automatico
  if not exists (
    select 1 from pg_constraint where conname = 'fk_solicitacoes_loja'
      and conrelid = 'public.solicitacoes'::regclass
  ) then
    begin
      alter table public.solicitacoes
        add constraint fk_solicitacoes_loja
        foreign key (loja_id) references public.lojas(id);
    exception when others then
      raise notice 'fk_solicitacoes_loja nao criada (dados orfaos?): %', sqlerrm;
    end;
  end if;

  -- solicitacao_itens.produto_id -> produtos(id)
  if not exists (
    select 1 from pg_constraint where conname = 'fk_solicitacao_itens_produto'
      and conrelid = 'public.solicitacao_itens'::regclass
  ) then
    begin
      alter table public.solicitacao_itens
        add constraint fk_solicitacao_itens_produto
        foreign key (produto_id) references public.produtos(id);
    exception when others then
      raise notice 'fk_solicitacao_itens_produto nao criada (dados orfaos?): %', sqlerrm;
    end;
  end if;

  -- pedido_itens.produto_id -> produtos(id) (coluna nullable, SET NULL ao apagar produto)
  if not exists (
    select 1 from pg_constraint where conname = 'fk_pedido_itens_produto'
      and conrelid = 'public.pedido_itens'::regclass
  ) then
    begin
      alter table public.pedido_itens
        add constraint fk_pedido_itens_produto
        foreign key (produto_id) references public.produtos(id) on delete set null;
    exception when others then
      raise notice 'fk_pedido_itens_produto nao criada (dados orfaos?): %', sqlerrm;
    end;
  end if;
end $$;

-- ============================================================================
--  Esclarecimento sobre movimentacoes.unidade (double precision):
--  apesar do nome legado "unidade", a coluna armazena o PRECO UNITARIO da
--  movimentacao (numero). O codigo Rust/TS a le/escreve como number —
--  NAO renomear a coluna, isso quebraria o app.
-- ============================================================================
comment on column public.movimentacoes.unidade is
  'Preco unitario da movimentacao (double precision). Nome legado "unidade" mantido por compatibilidade com o app (Rust/TS); nao renomear.';

-- ============================================================================
--  Reparo de sequencias apos importar dados com IDs explicitos (seed).
--  Chamar via POST /rest/v1/rpc/repair_sequences
-- ============================================================================
create or replace function public.repair_sequences()
returns void language plpgsql security definer as $$
declare t text;
begin
  foreach t in array array[
    'lojas','categorias','fornecedores','produtos','usuarios','movimentacoes',
    'solicitacoes','solicitacao_itens','pedidos','pedido_itens','alertas'
  ] loop
    execute format(
      'select setval(pg_get_serial_sequence(''public.%I'', ''id''),
             coalesce((select max(id) from public.%I), 1));', t, t);
  end loop;
end $$;
